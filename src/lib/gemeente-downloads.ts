/** Where PBL publishes the per-gemeente packages. 2025 is the year available. */
const GEMEENTE_BASE =
  "https://dataportaal.pbl.nl/data/Startanalyse_aardgasvrije_buurten/2025/Gemeentes";

/**
 * The gemeente a CBS buurt code belongs to: "BU" + 4 gemeente digits + buurt.
 *
 * The same derivation public/pbl-buurt-select.js makes (line 60), and the two
 * must agree -- both answer "which gemeente is this buurt in" for the same
 * clicked feature. Only the gemeente half is numeric; the buurt half is
 * alphanumeric (BU0363FF03 in Amsterdam) and is not read here.
 */
export function gemeenteCodeOf(buurtCode: string): string {
  return `GM${buurtCode.slice(2, 6)}`;
}

/**
 * URL of one gemeente's data package, or null when PBL publishes none.
 *
 * Null is a real answer, not an error path: Ameland has no package, so the
 * caller must render something other than a link rather than emit a 404.
 *
 * The filename is encoded because many contain spaces and four contain
 * parentheses.
 */
export function gemeenteDownloadUrl(gemeenteCode: string): string | null {
  const file = GEMEENTE_FILES[gemeenteCode];
  return file ? `${GEMEENTE_BASE}/${encodeURIComponent(file)}` : null;
}

